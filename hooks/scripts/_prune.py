#!/usr/bin/env python3
"""Active prune (v2.6): DELETE outdated/superseded/duplicate entries from
the active workspace topic tree + workspace docs.

Walks (via topics_dir / docs_dir helpers — workspace-aware):
  - workspaces/<active>/**/*.md   (topic tree root, recursive; reserved
    subdirs docs/journal/skills are auto-skipped by the helper layer)
  - workspaces/<active>/docs/*.md (handoff/exp/ref/tools/files)

Skips:
  - journal/**   (raw log is permanent — distill via /mem-distill, not prune)
  - _index.md    (auto-regenerated by _moc.py)
  - lessons.md   (folder ledger; uses 5-field schema, not entry list)
  - docs/questions.md (v4.9 gap ledger, managed by _gaps.py — its `- Q-` lines
    are not entries; a near-duplicate question is `similar:`, never deleted)

Rules (entry-level, in order):
  1. Entry with `valid_until: YYYY-MM-DD` past today  → DELETE
  2. Entry with `(superseded|deprecated|obsolete)`     → DELETE
  3. Within-file Jaccard ≥ 0.85 duplicates             → DELETE shorter

v4.9 (spec §3.3): a file is written only when an entry was deleted — the
rewrite used to drop the trailing newline, so every prune rewrote every clean
file (new bytes, new mtime, a diff in the next sync). Each file is read,
pruned and written under `file_lock(f"entries-{ws}", 5)`, the lock every
read-modify-write of topic/docs files holds; a timeout skips that file.

All writes use safe_write (atomic).
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from _atomic import safe_write  # type: ignore
from _audit import log_prune_delete  # type: ignore
from _debug import log_debug  # type: ignore
from _home import active_workspace, docs_dir, gowth_home, list_workspaces, topics_dir  # type: ignore
from _lock import file_lock  # type: ignore

LOCK_TIMEOUT = 5.0
# docs/ files that are not entry lists (v4.9: the gap ledger, `_gaps.py`).
DOCS_SKIP = frozenset({"questions.md"})

ENTRY_RE = re.compile(r"^\s*[-*]\s+\[")
VALID_UNTIL_RE = re.compile(r"valid[_-]?until:\s*(\d{4}-\d{2}-\d{2})", re.IGNORECASE)
SUPERSEDED_RE = re.compile(r"\((?:superseded|deprecated|obsolete)\b", re.IGNORECASE)


def jaccard(a: str, b: str) -> float:
    sa = set(re.findall(r"\w{4,}", a.lower()))
    sb = set(re.findall(r"\w{4,}", b.lower()))
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / len(sa | sb)


def prune_file(path: Path, dry_run: bool, today_iso: str,
               audit_rel: str | None = None, ws: str | None = None,
               lock_timeout: float = LOCK_TIMEOUT,
               skipped: list | None = None) -> tuple[int, int]:
    """First-write-wins for Jaccard dups (safer for integrity vs longer-wins;
    a noisy paste containing a missed secret never overwrites a clean concise one).

    Audit reasons:
      - `expired`              valid_until in the past
      - `superseded`           explicit (superseded|deprecated|obsolete) marker
      - `duplicate-newer-dropped`  new entry is jaccard-dup of an earlier one

    v4.9: read → prune → write under `file_lock(f"entries-{ws}")` (a dry run
    writes nothing and takes no lock); on a lock timeout the file is skipped
    — returns (0, 0) and appends it to `skipped` when given.
    """
    if dry_run:
        return _prune_file_locked(path, True, today_iso, audit_rel)
    name = f"entries-{ws or active_workspace()}"
    try:
        with file_lock(name, timeout=lock_timeout):
            return _prune_file_locked(path, False, today_iso, audit_rel)
    except TimeoutError:
        log_debug("prune", f"skipped {path}: lock {name} held")
        if skipped is not None:
            skipped.append(path)
        return (0, 0)


def _prune_file_locked(path: Path, dry_run: bool, today_iso: str,
                       audit_rel: str | None) -> tuple[int, int]:
    try:
        text = path.read_text()
    except Exception:
        return (0, 0)
    # split("\n"), not splitlines(): keeps the trailing newline (a final "")
    # and never breaks a line at \x0c / \u2028 that read_text() left inside it.
    lines = text.split("\n")

    kept_lines: list[str] = []
    kept_entries: list[str] = []
    deleted = 0
    audit_entries: list[tuple[str, str]] = []

    i = 0
    while i < len(lines):
        line = lines[i]
        if ENTRY_RE.match(line):
            entry_block = [line]
            j = i + 1
            while j < len(lines) and (lines[j].startswith(" ") or lines[j].startswith("\t")) and lines[j].strip():
                entry_block.append(lines[j])
                j += 1
            entry_text = "\n".join(entry_block)

            drop = False
            drop_reason = ""
            m = VALID_UNTIL_RE.search(entry_text)
            if m and m.group(1) < today_iso:
                drop = True
                drop_reason = "expired"
            elif SUPERSEDED_RE.search(entry_text):
                drop = True
                drop_reason = "superseded"

            if not drop:
                # First-write-wins: if ANY earlier kept entry is jaccard-similar,
                # drop the new one. Earlier writes survive — integrity preserved.
                for prev in kept_entries:
                    if jaccard(entry_text, prev) >= 0.85:
                        drop = True
                        drop_reason = "duplicate-newer-dropped"
                        break

            if drop:
                deleted += 1
                audit_entries.append((drop_reason or "duplicate-newer-dropped", entry_text))
            else:
                kept_lines.extend(entry_block)
                kept_entries.append(entry_text)
            i = j
        else:
            kept_lines.append(line)
            i += 1

    if deleted and not dry_run:
        safe_write(path, "\n".join(kept_lines))
        if audit_rel:
            for reason, body in audit_entries:
                log_prune_delete(audit_rel, reason, body)
    return (deleted, len(kept_entries))


def collect_files(ws: str | None = None) -> list[Path]:
    out: list[Path] = []
    skip_names = {"_index.md", "_MAP.md", "lessons.md", "00-README.md"}
    # v4.8 (review C2): every reserved subdir, INCLUDING memory/ — Claude Code's
    # own auto-memory files (`- [Title](file.md)` index lines, `- [ ]` tasks)
    # match ENTRY_RE and were being deleted as superseded/duplicates.
    from _home import RESERVED_SUBDIRS  # type: ignore
    skip_subdirs = set(RESERVED_SUBDIRS)
    td = topics_dir(ws)
    if td.is_dir():
        for p in td.rglob("*.md"):
            if not p.is_file() or p.name in skip_names:
                continue
            try:
                rel = p.relative_to(td)
            except ValueError:
                continue
            if rel.parts and rel.parts[0] in skip_subdirs:
                continue
            out.append(p)
    dd = docs_dir(ws)
    if dd.is_dir():
        out.extend(p for p in dd.glob("*.md") if p.is_file() and p.name not in DOCS_SKIP)
    return sorted(out)


def _prune_workspace(ws: str | None, dry_run: bool, today_iso: str, gh: Path,
                     skipped: list | None = None) -> tuple[int, int, list[tuple[str, int, int]]]:
    total_deleted = 0
    total_kept = 0
    affected: list[tuple[str, int, int]] = []
    ws_name = ws or active_workspace()
    timeout = LOCK_TIMEOUT
    misses: list = [] if skipped is None else skipped
    for f in collect_files(ws_name):
        try:
            rel = str(f.relative_to(gh))
        except ValueError:
            rel = str(f)
        audit_rel = None if dry_run else rel
        before = len(misses)
        deleted, kept = prune_file(f, dry_run, today_iso, audit_rel=audit_rel, ws=ws_name,
                                   lock_timeout=timeout, skipped=misses)
        if len(misses) > before:
            # the holder is busy: the rest of this workspace only tries once
            # (a 5 s wait per file would outlast the Stop hook's budget)
            timeout = 0.0
        if deleted > 0:
            affected.append((rel, deleted, kept))
        total_deleted += deleted
        total_kept += kept
    return total_deleted, total_kept, affected


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--all-workspaces", action="store_true",
                     help="Prune all workspaces, not just the active one")
    args = ap.parse_args()

    gh = gowth_home()
    if not gh.is_dir():
        print(f"no ~/.gowth-mem directory; nothing to prune")
        return 0

    today_iso = date.today().isoformat()
    workspaces = list_workspaces() if args.all_workspaces else [None]

    total_deleted = 0
    total_kept = 0
    all_affected: list[tuple[str, int, int]] = []
    skipped: list = []
    for ws in workspaces:
        d, k, a = _prune_workspace(ws, args.dry_run, today_iso, gh, skipped)
        total_deleted += d
        total_kept += k
        all_affected.extend(a)

    prefix = "[dry-run] " if args.dry_run else ""
    if skipped:
        names = []
        for p in skipped:
            try:
                names.append(str(p.relative_to(gh)))
            except ValueError:
                names.append(str(p))
        print(f"{prefix}prune: skipped {len(skipped)} file(s) — entries lock held: {', '.join(names[:5])}")
    if not all_affected:
        print(f"{prefix}prune: nothing to drop. {total_kept} entries verified clean.")
        return 0
    print(f"{prefix}prune: deleted {total_deleted} entries across {len(all_affected)} files. {total_kept} entries kept.")
    for rel, d, k in all_affected:
        print(f"  {rel}: -{d} entries (now {k})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
